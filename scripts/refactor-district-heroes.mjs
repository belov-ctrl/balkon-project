for (const slug of SLUGS) {
  const hero = HEROES[slug];
  if (!hero) {
    failed.push({ slug, reason: 'missing in HEROES map' });
    continue;
  }

  const result = replaceHeroForSlug(content, slug, hero);
  if (result.ok) {
    content = result.content;
    updated++;
  } else {
    failed.push({ slug, reason: result.reason });
  }
}

